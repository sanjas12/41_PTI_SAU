#!/usr/bin/env bash

# Назначение: последовательно подготавливает зависимости и запускает сборку EXE.
# Сначала вызывается подготовительный скрипт init_pip.sh, затем toexe.sh.
# Скрипт прекращает работу при первой ошибке или обращении к неопределённой
# переменной. Сейчас scripts/init_pip.sh отсутствует в репозитории, поэтому до
# исправления имени/пути первый шаг завершится ошибкой и сборка не начнётся.

set -euo pipefail

SCRIPTS_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "=== Шаг 1: зависимости ==="
bash "$SCRIPTS_DIR/init_env.sh"

echo "=== Шаг 2: сборка ==="
bash "$SCRIPTS_DIR/toexe.sh"
