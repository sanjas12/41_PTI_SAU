#!/usr/bin/env bash

# Назначение: последовательно пересоздаёт окружение и запускает сборку EXE.
# Сначала вызывается recreate_env.sh, затем build.sh.
# Скрипт прекращает работу при первой ошибке или обращении к неопределённой
# переменной. Используйте его для полной сборки на чистом окружении; для обычной
# повторной сборки без удаления .venv запускайте build.sh напрямую.

set -euo pipefail

SCRIPTS_DIR="$(cd "$(dirname "$0")" && pwd)"

echo "=== Шаг 1: зависимости ==="
bash "$SCRIPTS_DIR/recreate_env.sh"

echo "=== Шаг 2: сборка ==="
bash "$SCRIPTS_DIR/build.sh"
